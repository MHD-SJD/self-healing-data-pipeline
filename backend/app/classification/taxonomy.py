from enum import Enum


class FailureCategory(str, Enum):
    MISSING_DATA = "MISSING_DATA"
    DUPLICATE_DATA = "DUPLICATE_DATA"
    SCHEMA_DRIFT = "SCHEMA_DRIFT"
    DISTRIBUTION_ANOMALY = "DISTRIBUTION_ANOMALY"
    INVALID_RECORDS = "INVALID_RECORDS"
    INGESTION_FAILURE = "INGESTION_FAILURE"
    TRANSFORMATION_FAILURE = "TRANSFORMATION_FAILURE"
    INFRASTRUCTURE_OR_TIMEOUT_FAILURE = "INFRASTRUCTURE_OR_TIMEOUT_FAILURE"
    UNKNOWN_FAILURE = "UNKNOWN_FAILURE"


class IncidentSeverity(str, Enum):
    INFO = "INFO"
    WARNING = "WARNING"
    ERROR = "ERROR"
    CRITICAL = "CRITICAL"


class IncidentStatus(str, Enum):
    OPEN = "OPEN"
    HEALING_IN_PROGRESS = "HEALING_IN_PROGRESS"
    RESOLVED = "RESOLVED"
    PENDING_APPROVAL = "PENDING_APPROVAL"
    ESCALATED_HUMAN_REQUIRED = "ESCALATED_HUMAN_REQUIRED"
    CANCELLED = "CANCELLED"


class RecoverySafetyLevel(str, Enum):
    AUTOMATIC = "AUTOMATIC"
    REQUIRES_APPROVAL = "REQUIRES_APPROVAL"
    MANUAL_ONLY = "MANUAL_ONLY"

